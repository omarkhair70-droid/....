import assert from 'node:assert/strict';
import {captureFragment} from '../formation.mjs';
import {emptyMind,makeMark,activeMark,correspondences,dismiss,validMind,topicKey,validBasis,captureBasis,rememberedMentions,validFieldBasis,composeFieldWork,validReality,meetReality} from '../living-intelligence.mjs';
const a={id:'a',title:'A',body:'Private. Need calibration.',mind:emptyMind()},b={id:'b',title:'B',body:'Offer calibration.',mind:emptyMind()};
const one='11111111-1111-4111-8111-111111111111',two='22222222-2222-4222-8222-222222222222';
a.mind.marks.push(makeMark({id:one,kind:'need',topic:'Calibration',fragment:captureFragment(a,9,a.body.length)}));
assert.equal(correspondences([a],a.id).links.length,0);
b.mind.marks.push(makeMark({id:two,kind:'ability',topic:' calibration ',fragment:captureFragment(b,0,0)}));
let result=correspondences([a,b],a.id);
assert.equal(result.links.length,1);assert.equal(result.links[0].local.excerpt,'Need calibration.');
assert.equal(result.links[0].kind,'hypothesis');
const basis=captureBasis(a.id,result.links[0]);
assert.equal(validBasis(basis,a.id),true);
assert.equal(validBasis(basis,b.id),false);
assert.equal(basis[1].mark.excerpt,'Offer calibration.');
assert.equal(validBasis([basis[0],basis[0]],a.id),false);
assert.equal(topicKey('إِدارة'),topicKey('ادارة'));
assert.equal(correspondences([a,b],b.id).links.length,1);
b.body='Edited.';assert.equal(activeMark(b,b.mind.marks[0]),false);assert.equal(correspondences([a,b],a.id).links.length,0);
b.body='Offer calibration.';a.mind=dismiss(a,result.links[0].key);
assert.equal(correspondences([a,b],b.id).links.length,0);assert.equal(validMind(a.mind),true);
assert.throws(()=>makeMark({id:two,kind:'fact',topic:'x',fragment:captureFragment(b,0,0)}));
assert.equal(validMind({marks:[b.mind.marks[0],b.mind.marks[0]],dismissed:[]}),false);
console.log('PASS: explicit meaning, exact source, local correspondences, invalidation and human challenge');

const draft={id:'draft',body:'What about calibration for our factory?'};
assert.equal(rememberedMentions([a,b,draft],draft.id).length,2);
assert.equal(rememberedMentions([b,draft],draft.id)[0].mark.excerpt,'Offer calibration.');
assert.equal(rememberedMentions([b,{...draft,body:'miscalibration'}],draft.id).length,0);
assert.equal(rememberedMentions([b,{...draft,body:'calibrations'}],draft.id).length,0);
assert.equal(rememberedMentions([{...b,body:'Edited.'},draft],draft.id).length,0);
assert.equal(rememberedMentions([a,b],a.id).length,0,'a marked topic does not masquerade as a fresh recall after challenge');
assert.equal(rememberedMentions([b,{...b,id:'duplicate'},draft],draft.id).length,0,'duplicate mark identities are excluded');
const ar={id:'ar',body:'نظام للمخزون',mind:emptyMind()};
ar.mind.marks.push(makeMark({id:'33333333-3333-4333-8333-333333333333',kind:'ability',topic:'إدارة المخزون',fragment:captureFragment(ar,0,0)}));
assert.equal(rememberedMentions([ar,{id:'now',body:'أفكر في اِدارة المخزون.'}],'now').length,1);
console.log('PASS: remembered subjects, exact boundaries and source invalidation without inferred role');

const materials=[{id:'scenario-0',kind:'scenario',text:'A team can build.'},{id:'local-1',kind:'local',text:'A factory needs help.',private:'Do not capture',voice:'Do not capture'}];
const formedInField=composeFieldWork({sources:materials,question:'Who will test it?',body:'A pilot.',id:'field-work',title:'A pilot.'});
assert.equal(validFieldBasis(formedInField.fieldBasis),true);
assert.deepEqual(formedInField.fieldBasis.sources,[{id:'scenario-0',kind:'scenario',text:'A team can build.'},{id:'local-1',kind:'local',text:'A factory needs help.'}]);
materials[0].text='Changed';formedInField.body='A revised pilot.';
assert.equal(formedInField.fieldBasis.sources[0].text,'A team can build.');
assert.equal(formedInField.fieldBasis.initial,'A pilot.');
assert.throws(()=>composeFieldWork({sources:[materials[0],materials[0]],question:'Question?',body:'A pilot.',id:'field-work',title:'A pilot.'}));
assert.throws(()=>composeFieldWork({sources:materials,question:' ',body:'A pilot.',id:'field-work',title:'A pilot.'}));
assert.equal(validFieldBasis({...formedInField.fieldBasis,sources:[{id:'x',kind:'verified',text:'Something'}]}),false);
console.log('PASS: disclosed field composition, independent evolution, provenance, and explicit uncertainty');

const observed=meetReality(formedInField,{id:'observation-1',kind:'scenario',observation:'No usable history.',source:'Fictional test',reading:'challenges',decision:'revise',revision:'Start with collection.',next:'Test data collection.'});
assert.equal(observed.body,'Start with collection.');
assert.equal(formedInField.body,'A revised pilot.');
assert.equal(observed.reality[0].before,'A revised pilot.');
assert.equal(observed.fieldBasis.initial,'A pilot.');
assert.equal(validReality(observed.reality),true);
const held=meetReality(observed,{id:'observation-2',kind:'reported',observation:'No answer yet.',source:'My own notes',reading:'unclear',decision:'hold',revision:'Do not apply',next:'Ask again.'});
assert.equal(held.body,observed.body);
assert.equal(held.reality[1].before,held.reality[1].after);
assert.throws(()=>meetReality(observed,{id:'bad',kind:'scenario',observation:'x',source:'',reading:'supports',decision:'hold',next:'Ask'}));
assert.equal(validReality([{...held.reality[0],kind:'verified'}]),false);
console.log('PASS: reality observations are authored, uncertain, provenance-tagged and independently retained');
